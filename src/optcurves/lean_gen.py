"""Generate Lean 4 / Mathlib theorems from three of the exact certificates in certificates/ (LEAN_TARGETS: h = 9/5
and 9317/5000 for n = 2, h = 19/10 for n = 3); the other certificates are checked in exact arithmetic only.

    python -m optcurves.lean_gen      # writes lean/Optcurves/Certificates.lean

Each theorem says: for any sequences x_k, g_k in a real inner-product space and reals f_k with
x_{k+1} = x_k - h g_k and the interpolation inequality of 1-smooth convex functions between every two
iterates, sum_k w_k v_k <= 0; a corollary rules out n consecutive violations.
The proof is the certificate: the multipliers lam and the LDL^T sum of squares are fed to `linarith`.
"""
import json
from pathlib import Path

import sympy as sp

ROOT = Path(__file__).resolve().parents[2]

# Certificates turned into Lean theorems (others are checked in SymPy only).
LEAN_TARGETS = ["n2_h9_5", "n2_h9317_5000", "n3_h19_10"]

HEADER = '''import Mathlib

/-!
# Exact certificates: gradient descent cannot break curve convexity n times in a row

Generated by `python -m optcurves.lean_gen` from `certificates/*.json`. Do not edit by hand.

Setting (L = 1; the general case follows by rescaling f): gradient descent `x (k+1) = x k - h • g k`,
`g k` the gradient and `f k` the value at `x k`. Curve violation `v k = 2 f k - f (k-1) - f (k+1)`.

**Scope.** The hypotheses are the interpolation inequalities of 1-smooth convex functions,
`f j + ⟪g j, x i - x j⟫ + ½‖g i - g j‖² ≤ f i`. Every 1-smooth convex function satisfies them
(Nesterov 2004, Thm 2.1.5), but that bridge lemma is *not* proved here.
-/

namespace Optcurves

variable {E : Type*} [NormedAddCommGroup E] [InnerProductSpace ℝ E]

/-- Interpolation inequality for a 1-smooth convex function between points `i` and `j`. -/
def Interp (xi xj gi gj : E) (fi fj : ℝ) : Prop :=
  fj + inner ℝ gj (xi - xj) + (1 / 2) * ‖gi - gj‖ ^ 2 ≤ fi

'''


def q(r):
    """Lean real literal for a rational."""
    r = sp.Rational(r)
    if r.q == 1:
        return f"({r.p} : ℝ)"
    return f"({r.p} / {r.q} : ℝ)"


def position(k, h):
    """x k written through x 0 and the gradients."""
    return " - ".join(["x 0"] + [f"{h} • g {j}" for j in range(k)])


def theorem(cert, name):
    n, N, h = cert["n"], cert["N"], q(cert["h"])
    w = cert["w"]
    viol = lambda k: f"(2 * f {k} - f {k - 1} - f {k + 1})"
    weighted = " + ".join(f"{q(w[k - 1])} * {viol(k)}" for k in range(1, n + 1))
    pairs = [tuple(map(int, key.split(","))) for key in cert["lam"]]
    lines = [
        f"/-- Step size h = {cert['h']} (≈ {float(sp.Rational(cert['h'])):.4f}), window of {n} consecutive "
        f"curve violations.",
        f"Weighted claim: {cert['claim'].replace('w_', 'w').replace('v_', 'v')} with w = ({', '.join(w)}).",
        f"Certificate: {len(pairs)} interpolation inequalities and {len(cert['sos'])} squares. -/",
        f"theorem {name}_weighted (x g : ℕ → E) (f : ℕ → ℝ)",
        f"    (hgd : ∀ k, x (k + 1) = x k - {h} • g k)",
        "    (hI : ∀ i j, Interp (x i) (x j) (g i) (g j) (f i) (f j)) :",
        f"    {weighted} ≤ 0 := by",
    ]
    for k in range(1, N + 1):
        if k == 1:
            lines.append(f"  have e1 : x 1 = {position(1, h)} := hgd 0")
        else:
            lines.append(f"  have e{k} : x {k} = {position(k, h)} := by")
            lines.append(f"    have h' := hgd {k - 1}; rw [e{k - 1}] at h'; exact h'")
    hyps = []
    for p, r in pairs:
        nm = f"q{p}{r}"
        hyps.append(nm)
        rws = [f"e{i}" for i in (p, r) if i > 0]
        lines.append(f"  have {nm} := hI {p} {r}")
        if rws:
            lines.append(f"  rw [{', '.join(rws)}] at {nm}")
    sq = []
    for k, term in enumerate(cert["sos"]):
        parts = [f"{q(c)} • (g {a} - g {N})" for a, c in enumerate(term["coeffs"]) if sp.Rational(c) != 0]
        lines.append(f"  have s{k} : 0 ≤ ‖{' + '.join(parts)}‖ ^ 2 := by positivity")
        sq.append(f"s{k}")
    all_h = " ".join(hyps + sq)
    lines += [
        f"  unfold Interp at {' '.join(hyps)}",
        f"  simp only [← real_inner_self_eq_norm_sq] at {all_h}",
        "  simp only [inner_add_left, inner_add_right, inner_sub_left, inner_sub_right,",
        f"    real_inner_smul_left, real_inner_smul_right] at {all_h}",
    ]
    vecs = ["x 0"] + [f"g {a}" for a in range(N + 1)]
    comm = [f"real_inner_comm ({u}) ({v})" for i, u in enumerate(vecs) for v in vecs[i + 1:]]
    lines.append("  linarith [" + ",\n    ".join(comm) + "]")
    lines.append("")
    pos = " ∧ ".join(f"0 < {viol(k)}" for k in range(1, n + 1))
    names = ", ".join(f"a{k}" for k in range(1, n + 1))
    lines += [
        f"/-- At h = {cert['h']}, the curve cannot be strictly concave at {n} consecutive steps. -/",
        f"theorem {name} (x g : ℕ → E) (f : ℕ → ℝ)",
        f"    (hgd : ∀ k, x (k + 1) = x k - {h} • g k)",
        "    (hI : ∀ i j, Interp (x i) (x j) (g i) (g j) (f i) (f j)) :",
        f"    ¬ ({pos}) := by",
        f"  rintro ⟨{names}⟩",
        f"  have := {name}_weighted x g f hgd hI",
        "  linarith",
        "",
    ]
    return "\n".join(lines)


def generate(targets=LEAN_TARGETS):
    body, names = [HEADER], []
    for stem in targets:
        cert = json.loads((ROOT / "certificates" / f"{stem}.json").read_text())
        name = "no_consecutive_" + stem
        body.append(theorem(cert, name))
        names += [name + "_weighted", name]
    body.append("end Optcurves\n")
    body += [f"#print axioms Optcurves.{nm}" for nm in names]
    return "\n".join(body) + "\n"


def main():
    out = ROOT / "lean" / "Optcurves" / "Certificates.lean"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(generate())
    print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
